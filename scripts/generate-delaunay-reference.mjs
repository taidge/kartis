// $taskTarget=(cargo metadata --no-deps --format-version 1 | ConvertFrom-Json).target_directory
// npm install --prefix (Join-Path $taskTarget 'd3-delaunay-reference') --no-audit --no-fund d3-delaunay@6.0.4 delaunator@5.1.0 robust-predicates@3.0.3
// No JavaScript or D3 is used by the Rust implementation at runtime.
import { readFile, writeFile } from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {join} from 'node:path';
const workspace=fileURLToPath(new URL('../',import.meta.url));
const target=JSON.parse(execFileSync('cargo',['metadata','--no-deps','--format-version','1'],{cwd:workspace,encoding:'utf8',windowsHide:true})).target_directory;
const reference=join(target,'d3-delaunay-reference','node_modules');
const {Delaunay}=await import(pathToFileURL(join(reference,'d3-delaunay/src/index.js')).href);
for(const [name,version] of [['d3-delaunay','6.0.4'],['delaunator','5.1.0'],['robust-predicates','3.0.3']]) {
  const actual=JSON.parse(await readFile(join(reference,name,'package.json'),'utf8')).version;
  if(actual!==version)throw Error(`Expected ${name}@${version}, found ${actual}`);
}
let seed = 0x651798b3;
function random() { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed; }
const orient=(a,b,c)=>BigInt(b[0]-a[0])*BigInt(c[1]-a[1])-BigInt(b[1]-a[1])*BigInt(c[0]-a[0]);
function incircle(a,b,c,d) {
  const [ax,ay,bx,by,cx,cy]=[a[0]-d[0],a[1]-d[1],b[0]-d[0],b[1]-d[1],c[0]-d[0],c[1]-d[1]].map(BigInt);
  return (ax*ax+ay*ay)*(bx*cy-by*cx)-(bx*bx+by*by)*(ax*cy-ay*cx)+(cx*cx+cy*cy)*(ax*by-ay*bx);
}
const cases=[];
for(let test=0;test<20;test++) {
  const points=[];
  while(points.length<5+test) {
    const p=[random()%2001-1000,random()%2001-1000];
    if(points.some(q=>q[0]===p[0]&&q[1]===p[1]))continue;
    let valid=true;
    for(let a=0;a<points.length;a++)for(let b=a+1;b<points.length;b++) {
      if(orient(points[a],points[b],p)===0n)valid=false;
      for(let c=b+1;c<points.length;c++)if(incircle(points[a],points[b],points[c],p)===0n)valid=false;
    }
    if(valid)points.push(p);
  }
  const d=Delaunay.from(points),links=new Set();
  for(let i=0;i<points.length;i++)for(const j of d.neighbors(i))links.add([Math.min(i,j),Math.max(i,j)].join(','));
  const edges=[...links].map(x=>x.split(',').map(Number)).sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
  const triangles=[];
  for(let i=0;i<d.triangles.length;i+=3)triangles.push([...d.triangles.slice(i,i+3)].sort((a,b)=>a-b));
  triangles.sort((a,b)=>a[0]-b[0]||a[1]-b[1]||a[2]-b[2]);
  cases.push(`Oracle { points: &[${points.map(p=>`[${p[0]}., ${p[1]}.]`).join(',')}], links: &[${edges.map(p=>`[${p}]`).join(',')}], triangles: &[${triangles.map(p=>`[${p}]`).join(',')}] }`);
}
const fixture=new URL('../tests/fixtures/delaunay_d3.rs',import.meta.url);
const output=`// Generated by scripts/generate-delaunay-reference.mjs using d3-delaunay 6.0.4, delaunator 5.1.0, robust-predicates 3.0.3.\n// Exact integer checks in the generator exclude all collinear triples and co-circular quadruples.\nconst ORACLES: &[Oracle] = &[\n${cases.join(',\n')}\n];\n`;
if(process.argv.includes('--check')){
  if((await readFile(fixture,'utf8')).replaceAll('\r\n','\n')!==output)throw Error('Frozen Delaunay oracle differs from the actual reference');
  console.log(`Verified ${cases.length} D3 oracle cases without modifying fixtures`);
}else{
  await writeFile(fixture,output);
  console.log(`Wrote ${cases.length} D3 oracle cases`);
}
