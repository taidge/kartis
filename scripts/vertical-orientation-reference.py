"""Freeze Unicode 16.0 UAX #50 orientation data and its compact Rust table.

Run python scripts/vertical-orientation-reference.py --check to verify the
checked-in artifacts against pinned official Unicode sources. Remove --check
to regenerate. Downloads use Cargo's workspace target_directory.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://www.unicode.org/Public/16.0.0/ucd"
SOURCES = {
    "VerticalOrientation-16.txt": ("VerticalOrientation.txt", "24ac1474554eb55c85ace5c16d551535a8c52cdc2f4c13cf68c3839214339bbe"),
    "DerivedGeneralCategory-16.txt": ("extracted/DerivedGeneralCategory.txt", "7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293"),
}


def records(data):
    for line in data.decode().splitlines():
        entry = line.split("#", 1)[0].strip()
        if not entry:
            continue
        span, value = (field.strip() for field in entry.split(";"))
        bounds = [int(code, 16) for code in span.split("..")]
        yield bounds[0], bounds[-1], value


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--no-deps", "--format-version", "1", "--offline", "--locked"], cwd=ROOT,
    ))
    cache = Path(metadata["target_directory"]) / "vertical-reference"
    cache.mkdir(parents=True, exist_ok=True)
    sources = {}
    for name, (url, digest) in SOURCES.items():
        path = cache / name
        if not path.exists():
            with urlopen(f"{BASE}/{url}", timeout=45) as response:
                path.write_bytes(response.read())
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"Unexpected source SHA-256 for {name}")
        sources[name] = data
    ranges = []
    for start, end, value in records(sources["VerticalOrientation-16.txt"]):
        if value == "R":
            continue
        if ranges and ranges[-1][1] + 1 == start and ranges[-1][2] == value:
            ranges[-1] = (ranges[-1][0], end, value)
        else:
            ranges.append((start, end, value))
    enclosing = [(start, end) for start, end, value in records(sources["DerivedGeneralCategory-16.txt"]) if value == "Me"]
    license_text = (ROOT / "tests/fixtures/bidi-unicode-LICENSE.txt").read_text(encoding="utf-8")
    lines = [
        "// Generated by scripts/vertical-orientation-reference.py. Unicode 16.0.0.",
        f"// Source {BASE}/VerticalOrientation.txt and extracted/DerivedGeneralCategory.txt",
        *["// " + line if line else "//" for line in license_text.splitlines()],
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub(super) enum VerticalOrientation { U, R, Tu, Tr }",
        "use VerticalOrientation::{U, Tu, Tr};",
        "const RANGES: &[(u32, u32, VerticalOrientation)] = &[",
        *[f"    (0x{start:X}, 0x{end:X}, {value})," for start, end, value in ranges],
        "];",
        "pub(super) fn orientation(c: char) -> VerticalOrientation {",
        "    let code = c as u32;",
        "    let index = RANGES.partition_point(|range| range.1 < code);",
        "    match RANGES.get(index) {",
        "        Some(&(start, _, value)) if start <= code => value,",
        "        _ => VerticalOrientation::R,",
        "    }",
        "}",
        "pub(super) fn enclosing(c: char) -> bool {",
        "    matches!(c as u32, " + " | ".join(f"0x{start:X}..=0x{end:X}" for start, end in enclosing) + ")",
        "}",
    ]
    # Use the repository formatter, with a scratch file inside target_directory.
    scratch = cache / "vertical_data.rs"
    scratch.write_text("\n".join(lines) + "\n", encoding="utf-8")
    subprocess.check_call(["rustfmt", "--edition", "2024", "--config", "skip_children=true", str(scratch)], cwd=ROOT)
    enclosing_text = "# Unicode 16.0 DerivedGeneralCategory.txt Me ranges\n"
    enclosing_text += f"# Source {BASE}/extracted/DerivedGeneralCategory.txt\n"
    enclosing_text += f"# SHA-256 {SOURCES['DerivedGeneralCategory-16.txt'][1]}\n"
    enclosing_text += "".join(f"{start:X}..{end:X};Me\n" for start, end in enclosing)
    outputs = {
        "src/render/raster/vertical_data.rs": scratch.read_bytes(),
        "tests/fixtures/vertical-orientation-unicode-16.txt": sources["VerticalOrientation-16.txt"],
        "tests/fixtures/vertical-enclosing-unicode-16.txt": enclosing_text.encode(),
    }
    for name, data in outputs.items():
        path = ROOT / name
        if args.check:
            if path.read_bytes() != data:
                raise ValueError(f"Fixture differs from {name}")
        else:
            path.write_bytes(data)


if __name__ == "__main__":
    main()
