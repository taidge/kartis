// Independent d3-scale 4.0.2 queries. Reference packages live under the normal
// workspace target_directory returned by cargo metadata; no runtime dependency.
import {execFileSync} from 'node:child_process';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const workspace = fileURLToPath(new URL('../', import.meta.url));
const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--no-deps', '--format-version', '1'], {cwd: workspace, encoding: 'utf8', windowsHide: true}));
const modules = join(metadata.target_directory, 'd3-color-reference', 'node_modules');
const load = name => import(pathToFileURL(join(modules, name, 'src/index.js')).href);
const [d3, {piecewise, interpolateRgb}] = await Promise.all([load('d3-scale'), load('d3-interpolate')]);
assert.equal(JSON.parse(await readFile(join(modules, 'd3-scale/package.json'))).version, '4.0.2');
assert.equal(JSON.parse(await readFile(join(modules, 'd3-interpolate/package.json'))).version, '3.0.1');
const unknown = [123,45,67,255], css = c => `rgba(${c[0]},${c[1]},${c[2]},${c[3]/255})`;
const num = value => typeof value === 'string' ? value : Number.isNaN(value) ? 'nan' : value === Infinity ? 'inf' : value === -Infinity ? '-inf' : Object.is(value, -0) ? '-0' : String(value);
const palettes = {sequential:[[5,30,90,255],[245,220,20,255]], diverging:[[10,30,80,64],[30,220,130,192],[220,30,40,255]]};
const configs = [
 ['linear',1,[-11,17],3], ['log',1,[1,1000],10], ['log',1,[-1000,-1],-10],
 ['pow',2,[-4,9],0], ['pow',0.3,[-5,20],2], ['pow',-1,[1,100],10], ['pow',-1,[-100,-1],-10],
 ['pow',-2,[0.5,10],2], ['sqrt',0.5,[-4,9],0], ['symlog',2,[-100,200],0], ['symlog',0.2,[-3,10],0.4],
];
const suffix = name => ({linear:'',log:'Log',pow:'Pow',sqrt:'Sqrt',symlog:'Symlog'})[name];
const configure = (scale, transform, parameter) => {
 if(transform==='pow') scale.exponent(parameter);
 if(transform==='symlog') scale.constant(parameter);
 return scale;
};
const rows = ['# Generated by scripts/nonlinear-color-reference.mjs from original d3-scale 4.0.2 functions.',
 '# record|id|kind|transform|parameter|domain0|domain1|midpoint|clamp|palette|query-or-offset|parameter-or-inverse|axis-position|original-rgba|profile'];
let cases=0, queries=0, inverses=0, nonfinite=0, interpolatorThrows=0;
for(const kind of ['sequential','diverging']) for(const [transform,parameter,domain,mid] of configs) for(const reverse of [false,true]) for(const constant of [false,true]) for(const clamp of [false,true]) for(const edgeMid of kind==='diverging'&&transform!=='linear'&&!constant?['middle','start','end']:['middle']) {
 const endpoints=constant?[domain[0],domain[0]]:reverse?[domain[1],domain[0]]:domain;
 const midpoint=constant?domain[0]:edgeMid==='start'?endpoints[0]:edgeMid==='end'?endpoints[1]:mid;
 const id=`${kind}-${transform}-${parameter}-${domain[0]}-${reverse?'reverse':'forward'}-${constant?'constant':'span'}-${clamp?'clamp':'extrapolate'}${edgeMid==='middle'?'':`-edge-${edgeMid}`}`;
 const palette=palettes[kind], sfx=suffix(transform);
 const construct=()=>configure(d3[`scale${kind==='sequential'?'Sequential':'Diverging'}${sfx}`](),transform,parameter).domain(kind==='diverging'?[endpoints[0],midpoint,endpoints[1]]:endpoints).clamp(clamp).unknown('unknown');
 const unit=construct().interpolator(t=>t);
 const color=construct().interpolator(piecewise(interpolateRgb,palette.map(css))).unknown(css(unknown));
 const axis=configure(d3[`scale${transform==='linear'?'Linear':sfx}`](),transform,parameter).domain(endpoints).range([0,1]);
 const fields=[id,kind,transform,parameter,...endpoints,midpoint,Number(clamp),palette.map(c=>c.join(':')).join(';')];
 const probes=[undefined,NaN,-2000,-1000,-100,-10,-1,-0.1,-0,0,0.1,0.5,1,2,3,5,10,30,100,200,1000,2000,...endpoints,midpoint];
 for(const query of probes) {
  const result=unit(query), position=axis(query);
  let emitted, thrown;
  try { emitted=color(query); } catch(error) { assert(!Number.isFinite(result)); thrown=error.name; interpolatorThrows++; }
  const rgba=emitted?.match(/[+-]?(?:\d*\.?\d+)(?:e[+-]?\d+)?/gi).map(Number);
  if(rgba){if(rgba.length===3)rgba.push(1);rgba[3]=Math.round(rgba[3]*255);}
  const profile=typeof result==='number'&&!Number.isFinite(result)?'nonfinite-parameter-unknown':'d3-result';
  if(profile!=='d3-result')nonfinite++;
  rows.push(['C',...fields,query===undefined?'missing':num(query),num(result),num(position),rgba?rgba.join(':'):`throws:${thrown}`,profile].join('|'));queries++;
 }
 for(const offset of [0,0.1,0.25,0.5,0.75,0.9,1]) {
  rows.push(['I',...fields,offset,num(axis.invert(offset)),'','','d3-inverse'].join('|'));inverses++;
 }
 cases++;
}
const files={};for(const file of ['sequential.js','diverging.js','log.js','pow.js','symlog.js'])files[`d3-scale/src/${file}`]=createHash('sha256').update(await readFile(join(modules,'d3-scale/src',file))).digest('hex');
const manifest={generator:'scripts/nonlinear-color-reference.mjs',package:'d3-scale',version:'4.0.2',sources:files,cases,queries,inverses,nonfiniteParameterQueries:nonfinite,interpolatorThrows,
 profileDifferences:['Finite source queries are passed through original D3 transforms before clamping, including negative-power opposite-sign extrapolation and zero infinities.', 'Non-finite final color parameters map to Rust unknown instead of using a D3 interpolator-specific NaN color.', 'Rust domains reject zero/cross-zero log or negative-power branches, collapsed/non-finite transformed spans or coefficients and exponent zero.','Missing is represented by JavaScript undefined, without null numeric coercion.']};
const outputs=[['nonlinear-color-d3.csv',rows.join('\n')+'\n'],['nonlinear-color-d3-source.json',JSON.stringify(manifest,null,2)+'\n']];
for(const [file,contents] of outputs){const path=new URL(`../tests/fixtures/${file}`,import.meta.url);if(process.argv.includes('--check'))assert.equal(await readFile(path,'utf8'),contents,`${file} drifted`);else await writeFile(path,contents);}
console.log(JSON.stringify({package:manifest.package,version:manifest.version,cases,queries,inverses,nonfiniteParameterQueries:nonfinite,interpolatorThrows,checked:process.argv.includes('--check')}));
