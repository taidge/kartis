// npm install --prefix (Join-Path $taskTarget 'd3-color-reference') --no-save --package-lock=false d3-scale@4.0.2 d3-interpolate@3.0.1 d3-color@3.1.0
import {execFileSync} from 'node:child_process';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {join} from 'node:path';
import {mkdir,writeFile} from 'node:fs/promises';
const workspace=fileURLToPath(new URL('../',import.meta.url));
const metadata=JSON.parse(execFileSync('cargo',['metadata','--no-deps','--format-version','1'],{cwd:workspace,encoding:'utf8',windowsHide:true}));
const reference=join(metadata.target_directory,'d3-color-reference','node_modules');
const [{scaleSequential,scaleDiverging,scaleQuantize},{piecewise,interpolateRgb}]=await Promise.all([
  import(pathToFileURL(join(reference,'d3-scale/src/index.js')).href),
  import(pathToFileURL(join(reference,'d3-interpolate/src/index.js')).href),
]);
const unknown=[123,45,67,255],css=c=>`rgba(${c[0]},${c[1]},${c[2]},${c[3]/255})`;
const palettes=[[[10,30,80,255],[240,220,20,255]],[[10,30,80,255],[30,220,130,255],[220,30,40,255],[240,220,20,255]],[[10,30,80,64],[30,220,130,192],[220,30,40,255]]];
const adjacent=(value,direction)=>{if(value===0)return direction*Number.MIN_VALUE;const v=new DataView(new ArrayBuffer(8));v.setFloat64(0,value);v.setBigUint64(0,v.getBigUint64(0)+(value>0?BigInt(direction):-BigInt(direction)));return v.getFloat64(0);};
const rows=['# Generated by scripts/color-scale-reference.mjs; independent d3-scale 4.0.2, d3-interpolate 3.0.1, d3-color 3.1.0.','kind|domain0|domain1|midpoint|clamp|palette|value|r|g|b|a'];
for(const kind of ['sequential','diverging','quantize'])for(const variant of kind==='quantize'?[0,1]:[0])for(const constant of [false,true])for(const clamp of [false,true]){
  const domain=constant?[5,5]:variant===1?[-10,10]:[-11,17],mid=constant?5:3,palette=palettes[kind==='diverging'||variant===1?2:kind==='quantize'?1:0];
  const scale=(kind==='sequential'?scaleSequential().domain(domain).interpolator(piecewise(interpolateRgb,palette.map(css))).clamp(clamp):kind==='diverging'?scaleDiverging().domain([domain[0],mid,domain[1]]).range(palette.map(css)).clamp(clamp):scaleQuantize().domain(domain).range(palette.map(css))).unknown(css(unknown));
  const probes=[null,NaN,-20,-11,-10.999, -4.000000001,-4,0,2.999999999,3,4.999999999,5,5.000000001,9.999999999,10,16.999,17,30];
  if(kind==='quantize')for(const boundary of scale.thresholds())probes.push(adjacent(boundary,-1),boundary,adjacent(boundary,1));
  for(const value of probes){
    // Our explicit unclamped-quantize extension is tested separately. D3
    // always clamps, so do not call its result an oracle for that extension.
    if(kind==='quantize'&&!clamp&&Number.isFinite(value)&&(value<domain[0]||value>domain[1]))continue;
    // Option::None is an absent argument (undefined), not JS null coercion.
    // Read D3's emitted CSS channels directly. Re-parsing with d3-color
    // deliberately erases RGB at alpha zero, losing the emitted RGBA data.
    const channels=scale(value===null?undefined:value).match(/[+-]?(?:\d*\.?\d+)(?:e[+-]?\d+)?/gi).map(Number);
    const out={r:channels[0],g:channels[1],b:channels[2],opacity:channels[3]??1};
    rows.push([kind,...domain,mid,Number(clamp),palette.map(c=>c.join(':')).join(';'),value===null?'missing':Number.isNaN(value)?'nan':value,out.r,out.g,out.b,Math.round(out.opacity*255)].join('|'));
  }
}
await mkdir(new URL('../tests/fixtures/',import.meta.url),{recursive:true});
await writeFile(new URL('../tests/fixtures/color-scale-d3.csv',import.meta.url),rows.join('\n')+'\n');
console.log(`${rows.length-2} independent color queries written`);
