// Evaluate this expression and call it with a real Playwright page.
(async (page, url = 'http://127.0.0.1:8813') => {
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const assert=(condition,message)=>{if(!condition)throw Error(message);};
  const flush=async()=>{
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    await page.evaluate(()=>window.fixture.flush_fixture());
  };
  await page.setViewportSize({width:1100,height:900});
  await page.goto(url);
  await page.waitForFunction(()=>window.fixtureReady===true);
  assert(await page.locator('.kartis-datum').count()===2,'Initial data buttons missing');
  assert(await page.locator('.kartis-mark svg,svg.kartis-mark').count()===2,'Glory SVG graphics missing');
  const clip=await page.evaluate(()=>{
    const p=document.querySelector('.kartis-plot').getBoundingClientRect();
    const c=document.querySelector('.kartis-mark-clip').getBoundingClientRect();
    const g=document.querySelector('.kartis-mark').getBoundingClientRect();
    return {left:c.left-p.left,width:c.width,graphicLeft:g.left-p.left,graphicWidth:g.width};
  });
  assert(Math.abs(clip.left-30)<0.1&&Math.abs(clip.width-560)<0.1&&Math.abs(clip.graphicLeft)<0.1&&Math.abs(clip.graphicWidth-640)<0.1,'Per-mark CSS clip moved or rescaled the logical viewBox');
  const legend=page.locator('.kartis-legend-item').nth(0);
  await page.evaluate(()=>window.fixture.accept_legend_proposals(false));
  await legend.click();await flush();
  assert(await legend.getAttribute('aria-pressed')==='true','Controlled legend changed before acceptance');
  assert(await page.locator('.kartis-datum').count()===2,'Controlled legend removed rows before acceptance');
  await page.evaluate(()=>window.fixture.accept_legend_proposals(true));
  await legend.click();await flush();
  assert(await legend.getAttribute('aria-pressed')==='false','Accepted legend state not exposed');
  assert(await page.locator('.kartis-datum').count()===1,'Legend did not filter data');
  assert(await page.locator('.kartis-mark-clip').nth(0).evaluate(e=>getComputedStyle(e).display)==='none','Legend did not hide the plotted series');
  assert(await page.locator('.kartis-label').nth(0).evaluate(e=>getComputedStyle(e).display)==='none','Legend did not hide owned label');
  assert(await page.locator('.kartis-label').nth(1).evaluate(e=>getComputedStyle(e).display)!=='none','Legend hid another series label');
  await legend.click();await flush();
  assert(await page.locator('.kartis-datum').count()===2,'Legend could not restore series');
  await page.locator('.kartis-datum').nth(0).hover();await flush();
  assert(await page.locator('.kartis-tooltip').textContent()==='alpha: 10','Datum pointer entry did not show tooltip');
  await page.locator('.kartis-datum').nth(1).focus();await page.mouse.move(5,5);await flush();
  assert(await page.locator('.kartis-tooltip').textContent()==='beta: 20','Actual focus did not show tooltip');
  await page.keyboard.press('ArrowUp');await flush();
  await page.waitForFunction(()=>document.activeElement?.classList.contains('kartis-datum')&&document.activeElement.textContent.startsWith('alpha'));
  assert(await page.locator('.kartis-tooltip').textContent()==='alpha: 10','Arrow navigation did not confirm real focus');
  await page.keyboard.press('Enter');await flush();
  assert(await page.evaluate(()=>window.fixture.selected_id())==='datum-alpha','Keyboard activation did not publish selection');
  assert(await page.locator('.kartis-datum').nth(0).getAttribute('aria-pressed')==='true','Selected datum state missing');
  const dim=await page.locator('.kartis-mark').nth(1).evaluate(e=>Number(getComputedStyle(e).opacity));
  assert(Math.abs(dim-0.35)<0.001,'Active datum did not highlight relative to other series');
  await page.evaluate(()=>window.fixture.update_alpha(41));await flush();
  assert(await page.locator('.kartis-tooltip').textContent()==='alpha: 41','Reactive tooltip retained stale datum');
  await page.keyboard.press('Space');await flush();
  assert((await page.evaluate(()=>window.fixture.event_log())).includes('select:datum-alpha:41'),'Activation read stale datum after update');
  await page.evaluate(()=>{window.paintBeforeOrder=[...document.querySelectorAll('.kartis-paint-item')];window.fixture.mixed_paint_order();});await flush();
  const paintOrder=await page.locator('.kartis-paint-item').evaluateAll(items=>items.map(item=>item.classList.contains('kartis-label')?'label':'mark'));
  assert(paintOrder.join(',')==='mark,label,mark,label','Widget did not preserve arbitrary mixed geometry/text DOM order');
  assert(await page.evaluate(()=>{const after=[...document.querySelectorAll('.kartis-paint-item')],old=window.paintBeforeOrder;return after[0]===old[0]&&after[1]===old[2]&&after[2]===old[1]&&after[3]===old[3];}),'Paint reorder replaced existing DOM nodes');
  await page.evaluate(()=>window.fixture.reject_scene());await flush();
  assert((await page.evaluate(()=>window.fixture.event_log())).includes('reject:'),'Rejected scene did not report a diagnostic');
  assert(await page.locator('.kartis-datum').count()===2,'Rejected scene replaced the accepted model');
  await page.evaluate(()=>window.fixture.restore_scene());await flush();
  await page.evaluate(()=>{window.staleDatum=document.querySelector('.kartis-datum');window.fixture.remove_alpha();});await flush();
  assert(await page.locator('.kartis-datum').count()===1,'Removed datum retained a control');
  const before=await page.evaluate(()=>window.fixture.event_log());
  await page.evaluate(()=>window.staleDatum.click());await flush();
  assert(await page.evaluate(()=>window.fixture.event_log())===before,'Detached datum listener survived row retirement');
  await page.evaluate(()=>{window.staleDatum=document.querySelector('.kartis-datum');window.fixture.stop_fixture();});
  assert(await page.locator('#app').evaluate(e=>e.childElementCount)===0,'Widget teardown retained DOM nodes');
  assert(await page.evaluate(()=>window.fixture.live_nodes())===0,'Widget teardown retained semantic nodes');
  await page.evaluate(()=>window.staleDatum.click());
  await page.evaluate(()=>window.fixture.mount_fixture());await flush();
  assert(await page.locator('.kartis-datum').count()===2,'Fresh mount failed after listener teardown');
  assert(errors.length===0,errors.join('\n'));
  return {passed:true,legendControlled:true,ownedLabelVisibility:true,mixedPaintOrder:paintOrder,hoverFocusTooltip:true,actualKeyboardFocus:true,currentDatumActivation:true,rejectedUpdateRetained:true,retirement:true,remount:true,clip,pageErrors:errors};
})
