"""Generate original static 400/700 font fixtures and independent table records.

The glyphs are authored geometric test symbols, distributed under Apache-2.0.
Run with fonttools==4.67.0; --check compares regenerated bytes and references.
These are actual different outlines and advances, not duplicated font bytes
with changed names or synthetic bold rendering.
"""
import argparse
import io
import json
from pathlib import Path

import fontTools
from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent


def contour(pen, points):
    pen.moveTo(points[0])
    for point in points[1:]:
        pen.lineTo(point)
    pen.closePath()


def glyph(name, bold):
    pen = TTGlyphPen(None)
    width = 800 if bold else 400
    if name == "A":
        # A compact geometric cap with a genuinely different bold silhouette.
        contour(pen, [(20, 0), (width / 2 + 20, 700), (width + 20, 0),
                      (width - 80, 0), (width / 2 + 20, 450), (120, 0)])
        contour(pen, [(120, 180), (width - 80, 180), (width - 80, 260), (120, 260)])
    elif name in {"B", ".notdef", "alef", "bet"}:
        contour(pen, [(20, 0), (width + 20, 0), (width + 20, 700), (20, 700)])
        if name == "B":
            contour(pen, [(120, 100), (120, 600), (width - 80, 600), (width - 80, 100)])
    elif name == "A.vert":
        contour(pen, [(20, 0), (220, 0), (220, 900), (20, 900)])
    elif name == "acutecomb":
        contour(pen, [(0, 750), (100, 850), (180, 850), (80, 750)])
    return pen.glyph()


def build(weight):
    bold = weight == 700
    style = "Bold" if bold else "Regular"
    order = [".notdef", "space", "A", "B", "acutecomb", "alef", "bet", "A.vert"]
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder(order)
    builder.setupCharacterMap({32: "space", 65: "A", 66: "B", 0x301: "acutecomb",
                               0x5D0: "alef", 0x5D1: "bet"})
    glyphs = {name: glyph(name, bold) for name in order}
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({
        name: (0 if name == "acutecomb" else 1000 if bold else 600,
               getattr(value, "xMin", 0)) for name, value in glyphs.items()
    })
    builder.setupHorizontalHeader(ascent=900, descent=-100)
    builder.setupVerticalMetrics({name: (1000, 1000 - getattr(value, "yMax", 0))
                                  for name, value in glyphs.items()})
    builder.setupVerticalHeader(ascent=500, descent=-500)
    builder.setupOS2(sTypoAscender=900, sTypoDescender=-100,
                     usWinAscent=1000, usWinDescent=100, usWeightClass=weight,
                     fsSelection=0x20 if bold else 0x40)
    family = "Kartis Fixture Typography"
    builder.setupNameTable({"familyName": family, "styleName": style,
        "uniqueFontIdentifier": family + " " + style, "fullName": family + " " + style,
        "psName": family.replace(" ", "") + "-" + style, "version": "Version 1.000",
        "copyright": "Original Kartis fixture artwork. Apache-2.0.",
        "licenseDescription": "Licensed under the Apache License, Version 2.0.",
        "licenseInfoURL": "https://www.apache.org/licenses/LICENSE-2.0"})
    builder.setupPost()
    font = builder.font
    font["head"].macStyle = 1 if bold else 0
    addOpenTypeFeaturesFromString(font, "feature vert { sub A by A.vert; } vert;")
    font.recalcTimestamp = False
    font["head"].created = font["head"].modified = 3406620150
    output = io.BytesIO()
    font.save(output, reorderTables=False)
    return output.getvalue()


def reference(data):
    # Read serialized tables independently from Rust's ttf-parser/rustybuzz.
    font = TTFont(io.BytesIO(data))
    return {
        "weight": font["OS/2"].usWeightClass,
        "units_per_em": font["head"].unitsPerEm,
        "glyphs": {name: {
            "advance": font["hmtx"][name][0],
            "bounds": [font["glyf"][name].xMin, font["glyf"][name].yMin,
                       font["glyf"][name].xMax, font["glyf"][name].yMax],
        } for name in ["A", "B", "A.vert", "alef", "bet"]},
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    if fontTools.__version__ != "4.67.0":
        raise SystemExit("Use fonttools==4.67.0 for deterministic fixtures")
    outputs = {}
    records = {}
    for style, weight in [("Regular", 400), ("Bold", 700)]:
        data = build(weight)
        outputs[ROOT / "tests" / "fonts" / f"KartisFixtureTypography-{style}.ttf"] = data
        records[style] = reference(data)
    outputs[ROOT / "tests" / "fixtures" / "typography-font-reference.json"] = (
        json.dumps(records, indent=2) + "\n").encode()
    outputs[ROOT / "tests" / "fonts" / "KartisFixtureTypography-LICENSE.txt"] = (
        "Kartis Fixture Typography\n\nOriginal geometric test glyphs by the Kartis contributors.\n"
        "Both Regular (400) and Bold (700) fonts, including their outlines, are\n"
        "distributed under the Apache License, Version 2.0.\n\n"
    ).encode() + (ROOT / "LICENSE").read_bytes()
    for path, data in outputs.items():
        if arguments.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f"Generated fixture differs: {path.relative_to(ROOT)}")
        else:
            path.write_bytes(data)


if __name__ == "__main__":
    main()
