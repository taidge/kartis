#[test]
fn checked_profile_and_axis_convenience_formats_preserve_rounding() {
    use kartis::ValueFormat;
    let locale = FormatLocale::default();
    for spec in [".21f", ".21e", ".22g", "257f", "q", "\n.2f"] {
        assert!(NumberFormat::new(spec, &locale).is_err(), "{spec:?}");
    }
    for value in [f64::NAN, f64::INFINITY, f64::NEG_INFINITY] {
        assert!(format_number("g", value, &locale).is_err());
        assert!(format_prefix(".2", value, &locale).is_err());
    }
    assert!(
        format_prefix(".2", 1e-24, &locale)
            .unwrap()
            .format(f64::MAX)
            .is_err()
    );
    assert!(format_text("c", &"x".repeat(1025), &locale).is_err());
    assert!(format_number(",b", f64::MAX, &locale).is_err());
    assert_eq!(format_number("b", f64::MAX, &locale).unwrap().len(), 1024);
    let expanded = FormatLocale {
        numerals: Some(std::array::from_fn(|_| "0123456789012345".into())),
        ..Default::default()
    };
    assert!(format_number("0256d", 1., &expanded).is_err());
    assert_eq!(ValueFormat::Fixed(1).format(1.25).unwrap(), "1.3");
    assert_eq!(ValueFormat::Auto.format(1.0625).unwrap(), "1.063");
    assert_eq!(ValueFormat::Scientific(0).format(-2.5).unwrap(), "-3e+0");
    assert_eq!(ValueFormat::Grouped(1).format(1234.25).unwrap(), "1,234.3");
    assert_eq!(ValueFormat::Compact(1).format(1250.).unwrap(), "1.3k");
    assert_eq!(
        ValueFormat::Affix {
            prefix: "[".into(),
            suffix: "]".into(),
            precision: 1
        }
        .format(1.25)
        .unwrap(),
        "[1.3]"
    );
    assert!(
        ValueFormat::Specifier(Box::new(NumberFormat::new("c", &locale).unwrap()))
            .validate()
            .is_err()
    );
    assert!(ValueFormat::Fixed(21).validate().is_err());
    assert_eq!(
        ValueFormat::Fixed(20).format(1.25).unwrap(),
        "1.25000000000000000000"
    );
    let below = f64::from_bits(1.25_f64.to_bits() - 1);
    let above = f64::from_bits(1.25_f64.to_bits() + 1);
    for spec in [".1f", ".1e", ".2g", ".2r", ".2s"] {
        let expected_below = if spec == ".1e" { "1.2e+0" } else { "1.2" };
        let expected_above = if spec == ".1e" { "1.3e+0" } else { "1.3" };
        assert_eq!(format_number(spec, below, &locale).unwrap(), expected_below);
        assert_eq!(format_number(spec, above, &locale).unwrap(), expected_above);
    }
}
